a = int(input("Enter the value of a: "))
b = int(input("Enter the value of b: "))

print(a," + ",b," = ",a+b)
print(a," - ",b," = ",a-b)
print(a," * ",b," = ",a*b)
print(a," / ",b," = ",a/b)
print(a," // ",b," = ",a//b)
print(a," % ",b," = ",a%b)
print(a," ** ",b," = ",a**b)

# Output
# Enter the value of a: 4
# Enter the value of b: 5
# 4  +  5  =  9
# 4  -  5  =  -1
# 4  *  5  =  20
# 4  /  5  =  0.8
# 4  //  5  =  0
# 4  %  5  =  4
# 4  **  5  =  1024
